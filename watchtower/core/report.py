def render_html(r: ReportInput, now: datetime | None = None) -> str:
    now = now or datetime.now(timezone.utc)
    a = r.assessment
    findings = [f for f in a.findings if r.include_info or f.severity != "Info"]
    counts = {s: sum(1 for f in findings if f.severity == s) for s in SEVERITIES}
    out = [f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' "
           f"content='width=device-width, initial-scale=1'><title>{_e(r.title)}</title><style>{CSS}</style>"
           "</head><body>",
           f"<h1>{_e(r.title)}</h1><div class='meta'>{now:%Y-%m-%d %H:%M} UTC"
           + (f" · {_e(r.author)}" if r.author else "") + f" · generated by Watchtower {__version__}</div>"]

    # executive summary
    worst = a.risks[0] if a.risks else None
    out.append("<h2>Executive summary</h2>")
    out.append(f"<p>{a.hosts_assessed} host(s) and {a.networks_assessed} Wi-Fi network(s) were assessed, with "
               f"{len(findings)} finding(s)"
               + (f". The highest-risk device is <strong>{_e(worst.label)}</strong> (risk {worst.score}/100)."
                  if worst and worst.findings else ".") + "</p>")
    out.append("<div class='cards'>" + "".join(
        f"<div class='card'><b style='color:{SEV_COLORS[s]}'>{counts[s]}</b>{s}</div>"
        for s in SEVERITIES if r.include_info or s != "Info") + "</div>")
    urgent = [f for f in findings if f.severity in ("Critical", "High") and not f.patched][:8]
    if urgent:
        out.append("<h4>Fix first</h4><ol>" + "".join(
            f"<li><strong>{_e(f.title)}</strong> on {_e(f.device_label)}"
            + (" (public exploit available)" if f.exploits else "") + "</li>" for f in urgent) + "</ol>")

    # scope
    out.append("<h2>Scope</h2>")
    out.append("<p>Only targets on the authorized list were actively tested; Wi-Fi networks were assessed from "
               "what they broadcast.</p>")
    if r.targets:
        out.append("<h4>Authorized targets</h4><p>" + ", ".join(f"<code>{_e(t)}</code>" for t in r.targets) + "</p>")
    if r.networks:
        out.append("<h4>Authorized Wi-Fi networks</h4><table><tr><th>SSID</th><th>BSSID</th><th>Security</th></tr>"
                   + "".join(f"<tr><td>{_e(n.get('ssid') or '(hidden)')}</td><td>{_e(n['bssid'])}</td>"
                             f"<td>{_e(n.get('security'))}</td></tr>" for n in r.networks) + "</table>")

    # top risks
    out.append("<h2>Top risks</h2><table><tr><th>Risk</th><th>Device</th><th>Type</th><th>Findings</th>"
               "<th>Worst</th></tr>")
    for d in a.risks:
        n = sum(1 for f in d.findings if r.include_info or f.severity != "Info")
        out.append(f"<tr><td><strong>{d.score}</strong></td><td>{_e(d.label)}</td>"
                   f"<td>{'Wi-Fi' if d.kind == 'wifi' else 'Host'}</td><td>{n}</td><td>{_sev(d.worst)}</td></tr>")
    out.append("</table>")

    # findings per device
    out.append("<h2>Findings</h2>")
    by_dev: dict[str, list[Finding]] = {}
    for f in findings:
        by_dev.setdefault(f.device, []).append(f)
    order = [d.device for d in a.risks if d.device in by_dev]
    for dev in order:
        fs = sorted(by_dev[dev], key=lambda f: (SEV_RANK[f.severity], -(f.cvss or 0)))
        risk = a.risk_for(dev)
        out.append(f"<h3>{_e(fs[0].device_label)}" + (f" <span class='muted'>· risk {risk.score}/100</span>"
                                                      if risk else "") + "</h3>")
        out += [_finding_html(f) for f in fs]

    # changes
    if r.changes:
        out.append("<h2>Recent changes</h2><p>Differences between the two most recent scans of each target.</p>")
        for target, changes in r.changes.items():
            out.append(f"<h4>{_e(target)}</h4>")
            if not changes:
                out.append("<p class='muted'>No changes.</p>")
                continue
            out.append("<table><tr><th>Level</th><th>Change</th><th>Detail</th></tr>" + "".join(
                f"<tr><td style='color:{LEVEL_COLORS[c.level]};font-weight:600'>{c.level}</td><td>{_e(c.title)}</td>"
                f"<td>{_e(c.detail)}</td></tr>" for c in changes) + "</table>")

    # methodology
    out.append("<h2>Methodology</h2><p>Data was collected with standard tools (nmap, testssl.sh/SSLyze, net-snmp, "
               "iw/nmcli/airodump-ng). Version-based CVE matches are marked <em>probable</em> unless confirmed by an "
               "nmap script; Ubuntu/Debian backported fixes are checked against the package revision in the "
               "banner. Default-credential results are fingerprint matches; no logins were attempted. Risk = 6 × "
               "worst CVSS + finding weights (max 70) + 1 per open port (max 15), capped at 100.</p>")
    if r.commands:
        out.append("<h4>Commands run</h4><table><tr><th>Time (UTC)</th><th>Purpose</th><th>Command</th><th>Exit</th>"
                   "</tr>" + "".join(
                       f"<tr><td>{_e(c['ts'][:19].replace('T', ' '))}</td><td>{_e(c.get('purpose', ''))}</td>"
                       f"<td class='cmd'>{_e(c['command'])}</td><td>{_e(c.get('exit_code', ''))}</td></tr>"
                       for c in r.commands) + "</table>")
    out.append("</body></html>")
    return "\n".join(out)


def _sev(s: str) -> str:
    return f"<span class='sev' style='background:{SEV_COLORS.get(s, '#757575')}'>{_e(s)}</span>"


def _finding_html(f: Finding) -> str:
    parts = [f"<div class='finding' style='border-left-color:{SEV_COLORS[f.severity]}'>",
             f"<h3>{_sev(f.severity)} {_e(f.title)}</h3>"]
    meta = []
    if f.service:
        meta.append(_e(f.service))
    if f.cve_id:
        meta.append(", ".join(f"<a href='https://nvd.nist.gov/vuln/detail/{_e(c.strip())}'>{_e(c.strip())}</a>"
                              for c in f.cve_id.split(",")))
    if f.cvss is not None:
        meta.append(f"CVSS {f.cvss:.1f}")
    meta.append(_e(f.confidence))
    parts.append(f"<div class='muted'>{' · '.join(meta)}</div>")
    parts.append("<h4>What was found</h4>" + _md(f.description))
    if f.patch_check.get("explanation"):
        parts.append("<h4>Is it fixed?</h4>" + _md(f.patch_check["explanation"]))
    if f.exploits:
        parts.append("<h4>Public exploit modules</h4><p>" + ", ".join(f"<code>{_e(m['module'])}</code>"
                                                                      for m in f.exploits) + "</p>")
    if f.technique:
        parts.append("<h4>How the attack works</h4>" + _md(f.technique))
    parts.append("<h4>How to fix it</h4>" + _md(f.remediation))
    if f.attck:
        parts.append("<h4>MITRE ATT&amp;CK</h4><p>" + ", ".join(
            f"<a href='{attck_mapping.url(t)}'>{_e(t)}</a> {_e(attck_mapping.name(t))}" for t in f.attck) + "</p>")
    parts.append("</div>")
    return "".join(parts)


# ---- PDF ----

def pdf_argv(html_path: str, pdf_path: str) -> list[str] | None:
    """WeasyPrint command line (Python module in Watchtower's env, or the system CLI)."""
    import importlib.util
    if importlib.util.find_spec("weasyprint") is not None:
        return [sys.executable, "-m", "weasyprint", html_path, pdf_path]
    cli = deps.find_binary("weasyprint")
    return [cli, html_path, pdf_path] if cli else None
