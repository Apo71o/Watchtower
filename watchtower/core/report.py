"""Pentest-style report: one self-contained HTML file (optional PDF via WeasyPrint).

Built from the same Assessment as the Findings tab, plus scope, recent changes
and the commands that produced the data (from the audit log).
"""

from __future__ import annotations

import html
import re
import sys
from dataclasses import dataclass, field
from datetime import datetime, timezone

from watchtower import __version__
from watchtower.core import attck_mapping, deps
from watchtower.core.assessment import Assessment
from watchtower.core.findings_engine import SEV_RANK, SEVERITIES, Finding
from watchtower.core.history_diff import Change

SEV_COLORS = {"Critical": "#b71c1c", "High": "#e53935", "Medium": "#ef6c00", "Low": "#f9a825", "Info": "#757575"}
LEVEL_COLORS = {"alert": "#c62828", "notice": "#ef6c00", "good": "#2e7d32", "info": "#757575"}


@dataclass
class ReportInput:
    assessment: Assessment
    title: str = "Network security assessment"
    author: str = ""
    targets: list[str] = field(default_factory=list)
    networks: list[dict] = field(default_factory=list)          # authorized Wi-Fi rows
    changes: dict[str, list[Change]] = field(default_factory=dict)  # target -> latest diff
    commands: list[dict] = field(default_factory=list)          # audit-log command rows
    include_info: bool = False


def _e(s) -> str:
    return html.escape(str(s if s is not None else ""))


def _md(s: str) -> str:
    """The tiny subset of Markdown used in finding texts: **bold**, `code`, paragraphs."""
    t = _e(s)
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"`(.+?)`", r"<code>\1</code>", t)
    return "".join(f"<p>{p.strip()}</p>" for p in t.split("\n\n") if p.strip())


